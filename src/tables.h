/*
 * Non-linear APU mixer (same curve as the old lookup tables, integer form).
 * pulse: ~95.52 / (8128/n + 100), tnd: ~163.67 / (24329/n + 100), scaled to s16.
 */
static inline s16 mix_pulse(int n) {
    if (n <= 0) return 0;
    return (s16)((3056640 * n) / (8128 + 100 * n));
}

static inline s16 mix_tnd(int n) {
    if (n <= 0) return 0;
    return (s16)((5218373 * n) / (24329 + 100 * n));
}

