/* Return glyph index or -1 for blank. */
static inline int font_gid(char ch) {
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 32);
    if (ch >= 'A' && ch <= 'Z') return 15 + (ch - 'A');
    if (ch >= '0' && ch <= '9') return 3 + (ch - '0');
    if (ch == '-') return 0;
    if (ch == '.') return 1;
    if (ch == '/') return 2;
    if (ch == ':') return 13;
    if (ch == '>') return 14;
    if (ch == '_') return 41;
    return -1;
}

