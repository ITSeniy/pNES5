static inline u32 nes_rgb(u8 idx) {
    u16 c = nes_palette565[idx & 63];
    u32 r = (u32)((c >> 11) & 31) * 255 / 31;
    u32 g = (u32)((c >> 5) & 63) * 255 / 63;
    u32 b = (u32)(c & 31) * 255 / 31;
    return 0xFF000000u | (r << 16) | (g << 8) | b;
}

